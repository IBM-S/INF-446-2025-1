def iter_polygons(geom):
    if geom is None:
        return []
    if isinstance(geom, Polygon):
        return [geom]
    if isinstance(geom, MultiPolygon):
        return list(geom.geoms)
    return []

def add_borough_boundaries_traces(fig: go.Figure, gdf_boro_4326: gpd.GeoDataFrame):
    legend_shown = set()
    for _, row in gdf_boro_4326.iterrows():
        nm_raw = str(row["boro_name"]).strip()
        nm_key = nm_raw.upper().strip()
        fill = BORO_COLORS.get(nm_key, "rgba(200,200,200,0.25)")
        group = nm_key

        for poly in iter_polygons(row.geometry):
            x, y = poly.exterior.xy
            show_leg = (group not in legend_shown)
            if show_leg:
                legend_shown.add(group)

            fig.add_trace(
                go.Scattermapbox(
                    lon=list(x),
                    lat=list(y),
                    mode="lines",
                    fill="toself",
                    fillcolor=fill,
                    line=dict(color="rgba(0,0,0,0.85)", width=1),
                    name=nm_raw,
                    legendgroup=group,
                    showlegend=show_leg,
                    hoverinfo="text",
                    text=nm_raw,
                )
            )

