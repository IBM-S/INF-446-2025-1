def load_borough_boundaries(boundaries_json: str | Path) -> gpd.GeoDataFrame:
    gdf = gpd.read_file(boundaries_json, driver="ESRIJSON")
    if gdf.crs is None:
        minx, miny, maxx, maxy = gdf.total_bounds
        looks_lonlat = (abs(minx) <= 180 and abs(maxx) <= 180 and abs(miny) <= 90 and abs(maxy) <= 90)
        gdf = gdf.set_crs(epsg=4326 if looks_lonlat else 2263)
    gdf = gdf.to_crs(epsg=4326)
    if "boro_name" not in gdf.columns:
        raise ValueError(f"No encuentro 'boro_name' en boundaries. Columnas: {list(gdf.columns)}")
    gdf["boro_name_norm"] = gdf["boro_name"].astype(str).str.upper().str.strip()
    return gdf[["boro_name", "boro_name_norm", "geometry"]].copy()

def iter_polygons(geom):
    if geom is None:
        return []
    if isinstance(geom, Polygon):
        return [geom]
    if isinstance(geom, MultiPolygon):
        return list(geom.geoms)
    return []

def plot_interactive(csv_path: str | Path, boundaries_json: str | Path):
    df = pd.read_csv(csv_path)

    # tipos seguros
    df["lat"] = pd.to_numeric(df["lat"], errors="coerce")
    df["lon"] = pd.to_numeric(df["lon"], errors="coerce")
    df["borough"] = df["borough"].astype(str).str.upper().str.strip()
    df = df.dropna(subset=["lat","lon"]).copy()
    df = df.replace({pd.NA: None})

    gdf_boro = load_borough_boundaries(boundaries_json)

    fig = go.Figure()

    # 1) Boundaries (pero SIN leyenda, para no duplicar)
    for _, row in gdf_boro.iterrows():
        b = row["boro_name_norm"]
        style = BORO_STYLE.get(b, {"fill":"rgba(200,200,200,0.15)", "pt":"#555"})
        for poly in iter_polygons(row.geometry):
            x, y = poly.exterior.xy
            fig.add_trace(go.Scattermapbox(
                lon=list(x), lat=list(y),
                mode="lines",
                fill="toself",
                fillcolor=style["fill"],
                line=dict(color="rgba(0,0,0,0.7)", width=1),
                name=b,                    # mismo nombre para agrupar
                legendgroup=b,             # 👈 mismo grupo que los puntos
                showlegend=False,          # 👈 clave: NO duplicar leyenda
                hoverinfo="text",
                text=b,
            ))

    # 2) Puntos (con leyenda): 1 item por borough
    hover_cols = [c for c in ["bg_id","COUNTY","TRACT","BLKGRP","TOTPOP10","POPDENS10","STATE"] if c in df.columns]

    for boro, sub in df.groupby("borough"):
        style = BORO_STYLE.get(boro, {"pt":"#555"})
        fig.add_trace(go.Scattermapbox(
            lat=sub["lat"],
            lon=sub["lon"],
            mode="markers",
            name=boro,               # 👈 este será el item de leyenda
            legendgroup=boro,        # 👈 al clickear, apaga puntos + boundaries
            marker=dict(size=5, opacity=0.70, color=style["pt"]),
            hovertext=sub["bg_id"].astype(str) if "bg_id" in sub.columns else None,
            hoverinfo="text",
            customdata=sub[hover_cols] if hover_cols else None,
        ))

    fig.update_layout(
        mapbox=dict(
            style="carto-positron",  # se ve más limpio que OSM
            center=NYC_CENTER,
            zoom=NYC_ZOOM,
        ),
        legend=dict(groupclick="togglegroup"),
        margin=dict(r=0, t=45, l=0, b=0),
        height=720,
        title="Centroides (TOTPOP10>0) por Borough + Boundaries (Interactivo)"
    )

    fig.show()

