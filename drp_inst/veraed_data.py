def rgba_str_to_mpl(color):
    """
    Convierte:
      - 'rgba(75, 192, 192, 0.18)' -> (0.294, 0.753, 0.753, 0.18)
      - (r,g,b,a) ya en tupla -> lo devuelve tal cual
      - '#ff7f0e' -> lo devuelve tal cual (matplotlib lo entiende)
    """
    if color is None:
        return None
    if isinstance(color, tuple) or isinstance(color, list):
        return tuple(color)
    if isinstance(color, str):
        s = color.strip()
        if s.startswith("#"):
            return s
        m = re.match(r"rgba?\(\s*([\d.]+)\s*,\s*([\d.]+)\s*,\s*([\d.]+)\s*(?:,\s*([\d.]+)\s*)?\)", s, re.I)
        if m:
            r = float(m.group(1)); g = float(m.group(2)); b = float(m.group(3))
            a = float(m.group(4)) if m.group(4) is not None else 1.0
            return (r/255.0, g/255.0, b/255.0, a)
    return color


