# 3) Spatial join: assign borough_geom (within -> intersects -> nearest)
# ============================================================
def assign_borough_by_geom(
    df_aed: pd.DataFrame,
    gdf_boro_4326: gpd.GeoDataFrame,
    print_examples: int = 10,
) -> gpd.GeoDataFrame:

    df_pts = df_aed.dropna(subset=["Latitude", "Longitude"]).copy()
    gdf_pts = gpd.GeoDataFrame(
        df_pts,
        geometry=gpd.points_from_xy(df_pts["Longitude"], df_pts["Latitude"]),
        crs="EPSG:4326"
    )

    gdf_boro = gdf_boro_4326.to_crs(gdf_pts.crs).copy()

    joined = gpd.sjoin(gdf_pts, gdf_boro, how="left", predicate="within")

    missing = joined["boro_name"].isna()
    if missing.any():
        fb = gpd.sjoin(gdf_pts[missing], gdf_boro, how="left", predicate="intersects")
        joined.loc[missing, "boro_name"] = fb["boro_name"].values
        joined.loc[missing, "boro_code"] = fb["boro_code"].values
        joined.loc[missing, "boro_name_norm"] = fb["boro_name_norm"].values

    still_missing = joined["boro_name"].isna()
    joined["nearest_distance_m"] = pd.NA

    if still_missing.any():
        pts_m = gdf_pts[still_missing].to_crs(epsg=2263)  # pies
        boro_m = gdf_boro.to_crs(epsg=2263)

        nearest = gpd.sjoin_nearest(
            pts_m,
            boro_m[["boro_name", "boro_code", "boro_name_norm", "geometry"]],
            how="left",
            distance_col="dist_ft"
        )
        nearest["dist_m"] = nearest["dist_ft"] * 0.3048

        idxs = nearest.index
        joined.loc[idxs, "boro_name"] = nearest["boro_name"].values
        joined.loc[idxs, "boro_code"] = nearest["boro_code"].values
        joined.loc[idxs, "boro_name_norm"] = nearest["boro_name_norm"].values
        joined.loc[idxs, "nearest_distance_m"] = nearest["dist_m"].values

        print(f"[NEAREST FALLBACK] Puntos fuera de geometría asignados por cercanía: {len(nearest)}")
        preview_cols = [c for c in ["Entity_Name", "Borough", "Latitude", "Longitude"] if c in joined.columns]
        preview = joined.loc[idxs, preview_cols + ["boro_name", "nearest_distance_m"]].copy()
        preview = preview.rename(columns={"boro_name": "borough_assigned"})
        preview = preview.sort_values("nearest_distance_m", ascending=False).head(print_examples)
        print("\nEjemplos (más lejos primero):")
        print(preview.to_string(index=False))

    joined = joined.rename(columns={"boro_name": "borough_geom", "boro_code": "borough_code"})
    joined["borough_geom_norm"] = joined["borough_geom"].astype(str).str.upper().str.strip()

    # Regla final: si por alguna razón queda NaN, lo dejamos como MANHATTAN
    joined["borough_final"] = joined["borough_geom_norm"].fillna("MANHATTAN").str.title()

    joined["is_mislabeled"] = False
    if "Borough_norm" in joined.columns:
        joined["is_mislabeled"] = joined["Borough_norm"].ne(joined["borough_geom_norm"])

    return joined.drop(columns=["index_right"], errors="ignore")


