def load_borough_boundaries(path: Path) -> gpd.GeoDataFrame:
    gdf = gpd.read_file(path, driver="ESRIJSON")

    if gdf.crs is None:
        minx, miny, maxx, maxy = gdf.total_bounds
        looks_like_lonlat = (abs(minx) <= 180 and abs(maxx) <= 180 and abs(miny) <= 90 and abs(maxy) <= 90)
        gdf = gdf.set_crs(epsg=4326 if looks_like_lonlat else 2263)

    gdf = gdf.to_crs(epsg=4326)

    if "boro_name" not in gdf.columns:
        raise ValueError("No encuentro columna 'boro_name' en boundaries.")
    if "boro_code" not in gdf.columns:
        gdf["boro_code"] = None

    gdf["boro_name_norm"] = gdf["boro_name"].astype(str).str.upper().str.strip()

    return gdf[["boro_name", "boro_code", "boro_name_norm", "geometry"]].copy()


