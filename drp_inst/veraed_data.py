def add_projected_xy(df: pd.DataFrame, lon_col: str, lat_col: str, epsg_out: int) -> pd.DataFrame:
    out = df.copy()
    out[lat_col] = pd.to_numeric(out[lat_col], errors="coerce")
    out[lon_col] = pd.to_numeric(out[lon_col], errors="coerce")
    out = out.dropna(subset=[lat_col, lon_col]).copy()

    gdf = gpd.GeoDataFrame(
        out,
        geometry=gpd.points_from_xy(out[lon_col], out[lat_col]),
        crs="EPSG:4326"
    ).to_crs(epsg=epsg_out)

    out["coordx"] = gdf.geometry.x
    out["coordy"] = gdf.geometry.y
    return out.drop(columns=["geometry"], errors="ignore")

