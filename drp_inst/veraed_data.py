import json
from pathlib import Path
import pandas as pd

COUNTY_NAMES = {
    "005": "Bronx County",
    "047": "Kings County",
    "061": "New York County",
    "081": "Queens County",
    "085": "Richmond County",
}

# Si quieres limitar a estos 5, déjalo así.
# Si quieres TODOS los counties que aparezcan, pon ALLOWED_COUNTIES = None
ALLOWED_COUNTIES = {"005", "047", "061", "081", "085"}

def load_json_file(path: str | Path) -> dict:
    path = Path(path)
    with path.open("r", encoding="utf-8") as f:
        return json.load(f)

def parse_features(payload: dict) -> list[dict]:
    rows = []
    for feat in payload.get("features", []):
        attrs = feat.get("attributes", {}) or {}
        c = feat.get("centroid", {}) or {}
        lon = c.get("x")
        lat = c.get("y")
        if lon is None or lat is None:
            continue

        # Normalizamos a strings con padding
        state = str(attrs.get("STATE", "")).zfill(2)
        county = str(attrs.get("COUNTY", "")).zfill(3)
        tract = str(attrs.get("TRACT", "")).zfill(6)
        blkgrp = str(attrs.get("BLKGRP", ""))  # suele ser 1 dígito

        rows.append({
            "STATE": state,
            "COUNTY": county,
            "TRACT": tract,
            "BLKGRP": blkgrp,
            "STATE_NAME": attrs.get("STATE_NAME", None),
            "ST_ABBREV": attrs.get("ST_ABBREV", None),
            "lon": float(lon),
            "lat": float(lat),
        })
    return rows

def build_df_from_files(json_paths: list[str | Path]) -> pd.DataFrame:
    all_rows = []
    for p in json_paths:
        payload = load_json_file(p)
        all_rows.extend(parse_features(payload))

    df = pd.DataFrame(all_rows)

    # ID único
    df["bg_id"] = df["STATE"] + df["COUNTY"] + df["TRACT"] + df["BLKGRP"].astype(str)

    # Nombre del county
    df["county_name"] = df["COUNTY"].map(COUNTY_NAMES).fillna("Unknown")

    # Filtrado opcional
    if ALLOWED_COUNTIES is not None:
        df = df[df["COUNTY"].isin(ALLOWED_COUNTIES)].copy()

    # Drop duplicados por seguridad (por paginación / mezcla)
    df = df.drop_duplicates(subset=["bg_id"]).reset_index(drop=True)

    return df

def county_summary(df: pd.DataFrame) -> pd.DataFrame:
    g = df.groupby(["COUNTY", "county_name"], dropna=False)
    summary = g.agg(
        n_points=("bg_id", "size"),
        lat_min=("lat", "min"),
        lat_max=("lat", "max"),
        lon_min=("lon", "min"),
        lon_max=("lon", "max"),
        lat_mean=("lat", "mean"),
        lon_mean=("lon", "mean"),
    ).reset_index()
    return summary.sort_values(["COUNTY"])

def export_by_county(df: pd.DataFrame, out_dir: str | Path = "out_counties"):
    out_dir = Path(out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)

    # CSV consolidado
    df[["bg_id", "STATE", "COUNTY", "TRACT", "BLKGRP", "county_name", "lat", "lon"]].to_csv(
        out_dir / "all_counties.csv", index=False
    )

    # CSV por county
    for county_code, sub in df.groupby("COUNTY"):
        cname = sub["county_name"].iloc[0].replace(" ", "_")
        out_path = out_dir / f"centroids_{county_code}_{cname}.csv"
        sub[["bg_id", "STATE", "COUNTY", "TRACT", "BLKGRP", "county_name", "lat", "lon"]].to_csv(out_path, index=False)
        print(f"[OK] guardado: {out_path} ({len(sub)} filas)")

