def load_json(path: Path) -> dict:
    with path.open("r", encoding="utf-8") as f:
        return json.load(f)

def parse_payload(payload: dict) -> list[dict]:
    rows = []
    for feat in payload.get("features", []) or []:
        attrs = feat.get("attributes", {}) or {}
        c = feat.get("centroid", {}) or {}

        lon = c.get("x", None)
        lat = c.get("y", None)
        if lon is None or lat is None:
            continue

        geoid = str(attrs.get("GEOID10", "")).strip()
        geoid = geoid.zfill(12) if geoid else ""

        # Derivar piezas desde GEOID10 (si viene bien formado)
        state = geoid[0:2] if len(geoid) >= 12 else None
        county = geoid[2:5] if len(geoid) >= 12 else str(attrs.get("COUNTY", "")).strip().zfill(3)
        tract = geoid[5:11] if len(geoid) >= 12 else None
        blkgrp = geoid[11] if len(geoid) >= 12 else None

        rows.append({
            "bg_id": geoid,
            "STATE": state,
            "COUNTY": str(county).zfill(3) if county is not None else None,
            "TRACT": tract,
            "BLKGRP": blkgrp,
            "STATE_NAME": attrs.get("STATE_NAME", None),
            "TOTPOP10": attrs.get("TOTPOP10", None),
            "POPDENS10": attrs.get("POPDENS10", None),
            "lon": float(lon),
            "lat": float(lat),
        })
    return rows

def build_df(json_files: list[Path]) -> pd.DataFrame:
    all_rows = []
    for p in json_files:
        payload = load_json(p)
        all_rows.extend(parse_payload(payload))

    df = pd.DataFrame(all_rows)

    # tipos
    df["STATE"] = df["STATE"].astype(str).str.zfill(2)
    df["COUNTY"] = df["COUNTY"].astype(str).str.zfill(3)
    df["TOTPOP10"] = pd.to_numeric(df["TOTPOP10"], errors="coerce")
    df["POPDENS10"] = pd.to_numeric(df["POPDENS10"], errors="coerce")

    # ✅ filtro extra pedido: solo Estado New York (FIPS 36)
    df = df[df["STATE"].eq(NY_STATE_FIPS)].copy()

    # NYC counties
    df = df[df["COUNTY"].isin(ALLOWED_COUNTIES)].copy()

    # borough
    df["borough"] = df["COUNTY"].map(COUNTY_TO_BOROUGH).fillna("UNKNOWN")

    # dedup por GEOID
    df = df.drop_duplicates(subset=["bg_id"]).reset_index(drop=True)

    return df


