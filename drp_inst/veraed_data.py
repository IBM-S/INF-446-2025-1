def signed_area(ring):
    # ring: list[[x,y], ...]
    area = 0.0
    for (x1, y1), (x2, y2) in zip(ring, ring[1:] + [ring[0]]):
        area += (x1 * y2 - x2 * y1)
    return area / 2.0

def esri_rings_to_multipolygon(rings):
    """
    Convierte rings ESRI -> MultiPolygon.
    Heurística: outer rings vs holes por orientación (área firmada).
    """
    if not rings:
        return None

    # Normaliza rings (asegura cierre)
    norm = []
    for r in rings:
        if not r:
            continue
        if r[0] != r[-1]:
            r = r + [r[0]]
        norm.append(r)

    # Separa outers/holes por orientación (esto puede variar, pero suele funcionar bien)
    outers = []
    holes = []
    for r in norm:
        a = signed_area(r)
        # En ArcGIS, comúnmente outer = clockwise (área firmada negativa)
        if a < 0:
            outers.append(r)
        else:
            holes.append(r)

    # Si por alguna razón no detectó outer, asumimos todos outers
    if not outers:
        outers = norm
        holes = []

    # Crea polígonos outer
    outer_polys = [Polygon(o) for o in outers if len(o) >= 4]

    # Asigna holes al outer que los contiene (por centroid)
    poly_holes = {i: [] for i in range(len(outer_polys))}
    for h in holes:
        if len(h) < 4:
            continue
        hpoly = Polygon(h)
        hc = hpoly.representative_point()
        assigned = False
        for i, op in enumerate(outer_polys):
            if op.contains(hc):
                poly_holes[i].append(h)
                assigned = True
                break
        # si no cae en ninguno, lo ignoramos (raro)

    polys = []
    for i, op in enumerate(outer_polys):
        try:
            polys.append(Polygon(op.exterior.coords, holes=poly_holes[i]))
        except Exception:
            polys.append(op)

    # Une en MultiPolygon (por si hay multipartes)
    merged = unary_union(polys)
    if merged.geom_type == "Polygon":
        return MultiPolygon([merged])
    if merged.geom_type == "MultiPolygon":
        return merged
    return None

def load_boroughs_from_json(path_json: str | Path) -> gpd.GeoDataFrame:
    path_json = Path(path_json)
    data = json.loads(path_json.read_text(encoding="utf-8"))

    # Caso A: GeoJSON
    if isinstance(data, dict) and data.get("type") == "FeatureCollection":
        gdf = gpd.read_file(path_json)
        # Asegura CRS
        if gdf.crs is None:
            gdf = gdf.set_crs("EPSG:4326")
        else:
            gdf = gdf.to_crs("EPSG:4326")
        # Normaliza nombres de columnas esperadas
        if "boro_name" not in gdf.columns and "boro_name" in (c.lower() for c in gdf.columns):
            # no siempre necesario
            pass
        return gdf[["boro_name", "boro_code", "geometry"]].copy()

    # Caso B: Esri JSON (pjson) típico de ArcGIS query
    # Estructura: {"features":[{"attributes":{...},"geometry":{"rings":[...]}}], "spatialReference": {...}}
    wkid = None
    if isinstance(data, dict):
        sr = data.get("spatialReference") or {}
        wkid = sr.get("wkid") or sr.get("latestWkid")

    rows = []
    for feat in data.get("features", []):
        attrs = feat.get("attributes", {}) or {}
        geom = feat.get("geometry", {}) or {}
        rings = geom.get("rings")
        if not rings:
            continue

        mp = esri_rings_to_multipolygon(rings)
        if mp is None:
            continue

        rows.append({
            "boro_name": attrs.get("boro_name"),
            "boro_code": attrs.get("boro_code"),
            "geometry": mp
        })

    gdf = gpd.GeoDataFrame(rows, geometry="geometry")

    # Asignar CRS según WKID si viene; si no, asumimos 4326
    # Tu query normalmente la hiciste con outSR=4326, así que 4326 es lo más probable.
    if wkid == 4326:
        gdf = gdf.set_crs("EPSG:4326")
    else:
        # si tu JSON venía en 2263 (NY State Plane ft), pon EPSG:2263 acá.
        # pero si no estás seguro, deja 4326.
        gdf = gdf.set_crs("EPSG:4326")

    return gdf[["boro_name", "boro_code", "geometry"]].copy()

