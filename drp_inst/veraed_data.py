                    lat=list(y),
                    mode="lines",
                    fill="toself",
                    fillcolor=fill,
                    line=dict(color="rgba(0,0,0,0.85)", width=1),
                    name=nm_raw,
                    legendgroup=group,
                    showlegend=show_leg,
                    hoverinfo="text",
                    text=nm_raw,
